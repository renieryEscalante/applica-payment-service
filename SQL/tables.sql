CREATE TABLE CUSTOMERS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255 CHAR) NOT NULL,
    COUNTRY VARCHAR2(100 CHAR) NOT NULL
);

CREATE TABLE PAYMENTS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER(19) NOT NULL,
    AMOUNT NUMBER(19, 2) NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) NOT NULL,
    STATUS VARCHAR2(50 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_PAYMENTS_CUSTOMERS
        FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(ID)
);

CREATE TABLE PAYMENT_PROCESS_LOG (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PAYMENT_ID NUMBER(19),
    ERROR_MESSAGE VARCHAR2(4000 CHAR) NOT NULL,
    ERROR_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
